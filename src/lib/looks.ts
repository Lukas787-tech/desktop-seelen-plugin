export function lookById(id: string): Look | undefined {
  return LOOKS.find((look) => look.id === id);
}

/** Just the appearance part of a config. */
export function pickAppearance(cfg: Appearance): Appearance {
  return Object.fromEntries(APPEARANCE_KEYS.map((key) => [key, cfg[key]])) as Appearance;
}

/** A look spelled out in full: its own values over the defaults. */
export function resolveLook(look: Look, defaults: Appearance): Appearance {
  return { ...pickAppearance(defaults), ...look.values };
}

/** The look the settings currently match exactly, if any - for a tick in a menu. */
export function currentLook(cfg: Appearance, defaults: Appearance): string | null {
  for (const look of LOOKS) {
    const want = resolveLook(look, defaults);
    if (APPEARANCE_KEYS.every((key) => Object.is(cfg[key], want[key]))) return look.id;
  }
  return null;
}

/** The marker an exported appearance carries, so a pasted recipe is recognised as one. */
const MARKER = '$desktopAppearance';

/**
 * The current appearance as text someone else can paste into their own surface.
 *
 * `shell` is the Desktop Surface theme's settings as stored, so an exported
 * rice carries the dock and the start menu as well as the desktop.
 */
export function exportAppearance(cfg: Pick<DesktopConfig, ShareKey>, shell: Record<string, string> = {}): string {
  const out: Record<string, unknown> = { [MARKER]: 1 };
  for (const key of [...APPEARANCE_KEYS, ...SHARED_EXTRA_KEYS]) out[key] = cfg[key];
  if (Object.keys(shell).length) out.shell = shell;
  return JSON.stringify(out, null, 2);
}

export type ParsedAppearance =
  | {
      ok: true;
      values: Partial<Pick<DesktopConfig, ShareKey>>;
      /** Theme settings as strings; pass them through `shareableShell` before writing. */
      shell: Record<string, string>;
      skipped: string[];
    }
  | { ok: false; error: string };

/**
 * Reads a pasted appearance back.
 *
 * Only keys this build knows are taken, and only when the value has the type
 * the default has - a recipe from a newer build, or a hand-edited one with a
 * typo, applies what it can and says what it left out rather than writing a
 * string into a slider.
 */
export function parseAppearance(text: string, defaults: Pick<DesktopConfig, ShareKey>): ParsedAppearance {
  let data: unknown;
  try {
    data = JSON.parse(text);
  } catch {
    return { ok: false, error: 'That is not valid JSON.' };
  }
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    return { ok: false, error: 'Expected an object of settings.' };
  }

  const known = new Set<string>([...APPEARANCE_KEYS, ...SHARED_EXTRA_KEYS]);
  const values: Record<string, unknown> = {};
  const shell: Record<string, string> = {};
  const skipped: string[] = [];
  for (const [key, value] of Object.entries(data)) {
    if (key === MARKER) continue;
    // The theme's settings, taken as strings; the caller keeps only real knobs.
    if (key === 'shell' && value && typeof value === 'object' && !Array.isArray(value)) {
      for (const [name, stored] of Object.entries(value)) {
        if (name.startsWith('--rs-') && typeof stored === 'string') shell[name] = stored;
        else skipped.push(`shell.${name}`);
      }
      continue;
    }
    if (!known.has(key)) {
      skipped.push(key);
      continue;
    }
    if (typeof value !== typeof defaults[key as ShareKey]) {
      skipped.push(key);
      continue;
    }
    values[key] = value;
  }
  if (!Object.keys(values).length && !Object.keys(shell).length) {
    return { ok: false, error: 'No appearance settings found in it.' };
  }
  return { ok: true, values: values as Partial<Pick<DesktopConfig, ShareKey>>, shell, skipped };
}
