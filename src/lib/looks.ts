import type { DesktopConfig } from './config.svelte';

/**
 * Looks: whole appearances, one click each - the equivalent of switching a
 * desktop's global theme, or of dropping someone's dotfiles into place.
 *
 * ## Why a look writes settings rather than being one
 *
 * The obvious design is a `look` setting that the stylesheets branch on. It
 * makes every other appearance setting a liar: choose Terminal, then set a
 * corner radius, and either the look ignores the slider or the slider silently
 * edits something the look then overrides. So a look is not a mode. It is a
 * set of values for the ordinary settings, written through the ordinary store,
 * after which every slider is still exactly what it says - and a look someone
 * has tuned is simply their own appearance, which is what a rice is.
 *
 * Each look is written as a *difference from the defaults* and applied as a
 * whole: a key it does not mention goes back to its default, so moving from
 * Retro to Glass leaves no bevel behind. A few settings are left out on
 * purpose - text size, whether anything animates and how fast - because those
 * are about the person using the desktop, not about how it is dressed.
 */

